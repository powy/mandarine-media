import React, { useState } from 'react';
import {
  List,
  Datagrid,
  TextField,
  DateField,
  Show,
  SimpleShowLayout,
  ShowButton,
  CreateButton,
  TopToolbar,
  ListButton,
  SearchInput,
  FilterButton,
  ExportButton,
  SelectInput,
  BooleanField,
  FunctionField,
  ReferenceInput,
  AutocompleteInput,
  ReferenceField,
  useRecordContext,
  useNotify,
  Button,
} from 'react-admin';
import { Alert, Chip, Box } from '@mui/material';
// Import from description reports API
import { getDescriptionReports, getDescriptionReport, getDescriptionReportsByBatch } from 'share';

// Define status choices
const reportStatusChoices = [
  { id: 'success', name: 'Success' },
  { id: 'failed', name: 'Failed' },
  { id: 'partial', name: 'Partial' },
];

// Define filters for the description reports list
const descriptionReportFilters = [
  <SearchInput
    source="q"
    placeholder="Search reports by title..."
    alwaysOn
    key="search"
  />,
  <SelectInput
    source="status"
    label="Status"
    choices={reportStatusChoices}
    key="status"
  />,
  <ReferenceInput
    source="description_id"
    reference="media-descriptions"
    label="Media Description"
    key="description"
  >
    <AutocompleteInput
      optionText="episode_title"
      filterToQuery={searchText => ({ episode_title: searchText })}
    />
  </ReferenceInput>,
];

const DescriptionReportListActions = () => (
  <TopToolbar>
    <FilterButton />
    <ExportButton />
    {/* No CreateButton since these are system-generated reports */}
  </TopToolbar>
);

// Status indicator component
const StatusIndicator = ({ record }) => {
  const getStatusColor = (success) => {
    return success ? 'success' : 'error';
  };

  const getStatusLabel = (success) => {
    return success ? 'Success' : 'Failed';
  };

  return (
    <Chip
      label={getStatusLabel(record.success_associated_file)}
      color={getStatusColor(record.success_associated_file)}
      size="small"
    />
  );
};

// Batch ID component with link to batch reports
const BatchIdField = () => {
  const record = useRecordContext();
  const notify = useNotify();

  const handleViewBatchReports = async () => {
    if (!record?.batch_id) return;

    try {
      const batchReports = await getDescriptionReportsByBatch(record.batch_id);
      notify(`Found ${batchReports.length} reports in batch ${record.batch_id}`, { type: 'info' });
      // TODO: Could open a dialog showing all batch reports
    } catch (error) {
      notify(`Error fetching batch reports: ${error.message}`, { type: 'error' });
    }
  };

  if (!record?.batch_id) {
    return <span>-</span>;
  }

  return (
    <Button
      onClick={handleViewBatchReports}
      label={`Batch ${record.batch_id.substring(0, 8)}...`}
      variant="text"
      size="small"
    />
  );
};

const DescriptionReportShowActions = () => (
  <TopToolbar>
    <ListButton label="Back to Reports" />
    {/* No EditButton since these are read-only reports */}
  </TopToolbar>
);

export const DescriptionReportList = () => (
  <>
    <Alert severity="info" sx={{ mb: 2 }}>
      <strong>Description Reports:</strong> These are system-generated reports tracking the success and failure
      of media description processing operations. Reports are read-only and automatically created by the system.
      Admin access only.
    </Alert>

    <List
      filters={descriptionReportFilters}
      actions={<DescriptionReportListActions />}
      sort={{ field: 'timestamp', order: 'DESC' }}
      perPage={25}
    >
      <Datagrid>
        <TextField source="id" label="Report ID" />

        <ReferenceField
          source="description_id"
          reference="media-descriptions"
          label="Media Description"
          link="show"
          sortable={false}
        >
          <TextField source="episode_title" />
        </ReferenceField>

        <TextField source="title" label="Report Title" sortable />

        <FunctionField
          label="Status"
          render={record => <StatusIndicator record={record} />}
        />

        <FunctionField
          label="Batch ID"
          render={() => <BatchIdField />}
          sortable={false}
        />

        <DateField
          source="timestamp"
          label="Created"
          showTime
          sortable
        />

        <ShowButton />
      </Datagrid>
    </List>
  </>
);


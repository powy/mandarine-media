import { describe, it, expect } from 'vitest';
import type {
  MediaDescription,
  MediaDescriptionCreate,
  VideoFile,
  VideoFileCreate,
  VideoFileUpdate,
} from '../types';

describe('v1.9 Type Changes and New Fields', () => {
  describe('MediaDescription v1.9 Changes', () => {
    it('should support renamed fields: tag_text_list and slug', () => {
      const mediaDescription: MediaDescription = {
        id: 'media-1',
        creation_date_utc: '2024-01-15T10:30:00Z',
        file_number: 1246,
        episode_title: 'Running Man - EP 730',
        media_type: 'video',
        
        // v1.9 renamed fields
        tag_text_list: ['drama', 'kpop', 'runningman', 'korea'], // was: human_keywords_text_list
        slug: 'running_man_ep_730', // was: friendly_url
        
        // Existing fields should still work
        descriptive_summary_text: 'Le thermomètre monte, mais le fun aussi !',
        production_year: 2024,
        is_featured: true,
      };

      expect(mediaDescription.tag_text_list).toEqual(['drama', 'kpop', 'runningman', 'korea']);
      expect(mediaDescription.slug).toBe('running_man_ep_730');
      expect(mediaDescription.episode_title).toBe('Running Man - EP 730');
      expect(mediaDescription.media_type).toBe('video');
    });

    it('should support MediaDescriptionCreate with v1.9 fields', () => {
      const createData: MediaDescriptionCreate = {
        file_number: 1247,
        episode_title: 'Running Man - EP 731',
        media_type: 'video',
        
        // v1.9 renamed fields
        tag_text_list: ['variety', 'korean', 'comedy'],
        slug: 'running_man_ep_731',
        
        // Optional fields
        descriptive_summary_text: 'Another great episode',
        production_year: 2024,
        program_id: 'program-running-man',
        season_id: 'season-2024',
        episode_number: 731,
        
        // Admin-only fields
        translation_share: 0.15,
        sacem_share: 0.05,
        revenue_share: 0.50,
        paid_token_cost: 100,
      };

      expect(createData.tag_text_list).toEqual(['variety', 'korean', 'comedy']);
      expect(createData.slug).toBe('running_man_ep_731');
      expect(createData.episode_number).toBe(731);
    });

    it('should handle auto-generated slug when not provided', () => {
      const createData: MediaDescriptionCreate = {
        file_number: 1248,
        episode_title: 'New Episode Title With Spaces',
        media_type: 'video',
        // slug not provided - should be auto-generated from episode_title
        tag_text_list: ['new', 'episode'],
      };

      // In actual implementation, slug would be auto-generated as: "new_episode_title_with_spaces"
      expect(createData.episode_title).toBe('New Episode Title With Spaces');
      expect(createData.tag_text_list).toEqual(['new', 'episode']);
      expect(createData.slug).toBeUndefined(); // Will be auto-generated by backend
    });

    it('should support all media types', () => {
      const mediaTypes: Array<'video' | 'webtoon' | 'trailer' | 'teaser' | 'excerpt' | 'season' | 'program'> = [
        'video', 'webtoon', 'trailer', 'teaser', 'excerpt', 'season', 'program'
      ];

      mediaTypes.forEach(mediaType => {
        const media: MediaDescriptionCreate = {
          file_number: 1000,
          episode_title: `Test ${mediaType}`,
          media_type: mediaType,
          slug: `test_${mediaType}`,
        };

        expect(media.media_type).toBe(mediaType);
      });
    });
  });

  describe('VideoFile v1.9 Changes', () => {
    it('should support new v1.9 fields', () => {
      const videoFile: VideoFile = {
        id: 'video-file-1',
        creation_date_utc: '2024-01-15T10:30:00Z',
        file_name: 'running_man_ep730.mp4',
        encoding_status: 'completed',
        upload_method: 'new_upload',
        upload_status: 'upload_completed',
        
        // v1.9 new fields
        environment_key: 'prod',
        protection_key: 'protected_content_123',
        slug: 'running_man_ep730', // auto-generated from file_name
        
        // Existing technical fields
        duration_seconds: 3600,
        file_size_bytes: 2147483648,
        video_codec: 'H.264',
        audio_codec: 'AAC',
        resolution_width: 1920,
        resolution_height: 1080,
        mux_asset_id: 'mux_asset_abc123',
        mux_playback_id: 'mux_playback_def456',
      };

      expect(videoFile.environment_key).toBe('prod');
      expect(videoFile.protection_key).toBe('protected_content_123');
      expect(videoFile.slug).toBe('running_man_ep730');
    });

    it('should support VideoFileCreate with v1.9 fields', () => {
      const createData: VideoFileCreate = {
        file_name: 'new_video.mp4',
        upload_method: 'new_upload',
        media_description_id: 'media-123',
        
        // v1.9 new fields
        environment_key: 'staging',
        protection_key: 'staging_protection_456',
        slug: 'new_video',
      };

      expect(createData.environment_key).toBe('staging');
      expect(createData.protection_key).toBe('staging_protection_456');
      expect(createData.slug).toBe('new_video');
      expect(createData.upload_method).toBe('new_upload');
    });

    it('should support VideoFileUpdate with v1.9 fields', () => {
      const updateData: VideoFileUpdate = {
        encoding_status: 'completed',
        duration_seconds: 1800,
        file_size_bytes: 1073741824,
        
        // v1.9 fields
        environment_key: 'prod',
        protection_key: 'updated_protection_789',
        slug: 'updated_video_slug',
        
        // Technical updates
        video_codec: 'H.265',
        resolution_width: 1920,
        resolution_height: 1080,
        drm_protection: true,
      };

      expect(updateData.environment_key).toBe('prod');
      expect(updateData.protection_key).toBe('updated_protection_789');
      expect(updateData.slug).toBe('updated_video_slug');
      expect(updateData.drm_protection).toBe(true);
    });

    it('should handle existing upload methods and statuses', () => {
      const uploadMethods: Array<'new_upload' | 'existing_url'> = ['new_upload', 'existing_url'];
      const uploadStatuses: Array<'metadata_only' | 'file_uploading' | 'upload_completed' | 'upload_failed'> = 
        ['metadata_only', 'file_uploading', 'upload_completed', 'upload_failed'];
      const encodingStatuses: Array<'pending' | 'processing' | 'completed' | 'failed'> =
        ['pending', 'processing', 'completed', 'failed'];

      uploadMethods.forEach(method => {
        const videoFile: VideoFile = {
          id: `video-${method}`,
          creation_date_utc: '2024-01-15T10:30:00Z',
          encoding_status: 'pending',
          upload_method: method,
          upload_status: 'metadata_only',
        };

        expect(videoFile.upload_method).toBe(method);
      });

      uploadStatuses.forEach(status => {
        const videoFile: VideoFile = {
          id: `video-${status}`,
          creation_date_utc: '2024-01-15T10:30:00Z',
          encoding_status: 'pending',
          upload_method: 'new_upload',
          upload_status: status,
        };

        expect(videoFile.upload_status).toBe(status);
      });

      encodingStatuses.forEach(status => {
        const videoFile: VideoFile = {
          id: `video-${status}`,
          creation_date_utc: '2024-01-15T10:30:00Z',
          encoding_status: status,
          upload_method: 'new_upload',
          upload_status: 'upload_completed',
        };

        expect(videoFile.encoding_status).toBe(status);
      });
    });
  });

  describe('Slug Generation Patterns', () => {
    it('should demonstrate expected slug patterns for MediaDescription', () => {
      const examples = [
        {
          episode_title: 'Running Man - EP 730',
          expected_pattern: 'running_man_ep_730'
        },
        {
          episode_title: 'My Amazing Show: Episode 1 (Special)',
          expected_pattern: 'my_amazing_show_episode_1_special'
        },
        {
          episode_title: 'K-Drama Romance 101',
          expected_pattern: 'k_drama_romance_101'
        }
      ];

      examples.forEach(example => {
        const media: MediaDescriptionCreate = {
          file_number: 1,
          episode_title: example.episode_title,
          media_type: 'video',
          // slug will be auto-generated following the pattern:
          // lowercase, spaces to underscores, special chars removed
        };

        expect(media.episode_title).toBe(example.episode_title);
        // Note: In real implementation, backend would generate the slug
      });
    });

    it('should demonstrate expected slug patterns for VideoFile', () => {
      const examples = [
        {
          file_name: 'running_man_ep730.mp4',
          expected_pattern: 'running_man_ep730'
        },
        {
          file_name: 'My Video File (HD).mov',
          expected_pattern: 'my_video_file_hd'
        },
        {
          file_name: 'special-episode_01.mkv',
          expected_pattern: 'special_episode_01'
        }
      ];

      examples.forEach(example => {
        const videoFile: VideoFileCreate = {
          file_name: example.file_name,
          upload_method: 'new_upload',
          // slug will be auto-generated from file_name
        };

        expect(videoFile.file_name).toBe(example.file_name);
        // Note: In real implementation, backend would generate the slug
      });
    });
  });

  describe('Type Safety', () => {
    it('should enforce required fields at compile time', () => {
      // This test ensures TypeScript compilation catches missing required fields
      
      const validMediaCreate: MediaDescriptionCreate = {
        file_number: 1,
        episode_title: 'Test Episode',
        media_type: 'video',
      };
      
      const validVideoFileCreate: VideoFileCreate = {
        // All fields are optional in VideoFileCreate
      };

      expect(validMediaCreate.file_number).toBe(1);
      expect(validMediaCreate.episode_title).toBe('Test Episode');
      expect(validMediaCreate.media_type).toBe('video');
      expect(validVideoFileCreate).toBeDefined();
    });

    it('should support optional v1.9 fields', () => {
      const mediaWithOptionalFields: MediaDescriptionCreate = {
        file_number: 1,
        episode_title: 'Test',
        media_type: 'video',
        // These v1.9 fields are optional
        tag_text_list: ['test'],
        slug: 'test_slug',
      };

      const mediaWithoutOptionalFields: MediaDescriptionCreate = {
        file_number: 1,
        episode_title: 'Test',
        media_type: 'video',
        // v1.9 fields omitted - should still be valid
      };

      expect(mediaWithOptionalFields.tag_text_list).toEqual(['test']);
      expect(mediaWithOptionalFields.slug).toBe('test_slug');
      expect(mediaWithoutOptionalFields.tag_text_list).toBeUndefined();
      expect(mediaWithoutOptionalFields.slug).toBeUndefined();
    });
  });
});